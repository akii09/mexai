import { describe, it, expect, vi, beforeEach } from 'vitest'
import { exportAgentsMd, exportClaudeMd, exportCursorRules } from './export-engine.js'

// ---------------------------------------------------------------------------
// Mocks
// ---------------------------------------------------------------------------

vi.mock('../store/store-manager.js', () => ({
  readLayer: vi.fn(),
}))

vi.mock('../store/config-manager.js', () => ({
  getTokenBudget: vi.fn(() => ({
    context: 250,
    codebase: 300,
    rules: 150,
    total: 700,
  })),
}))

import { readLayer } from '../store/store-manager.js'

const MOCK_CONTEXT = `---
name: My Project
slug: my-project
domain: web
stack:
  - TypeScript
status: active
createdAt: "2026-04-09T10:00:00.000Z"
updatedAt: "2026-04-09T10:00:00.000Z"
---

## Identity

Building a local-first AI context manager.

## Current State

Phase 2 complete.

## Decisions

## Open Threads

`

const MOCK_RULES = `# Agent Rules

## Code Quality

- Write tests for all new code
- No implicit any

## Review Gates

- Tests must pass before commit
`

const MOCK_CODEBASE = `# Codebase Map

## Key Files

- \`src/index.ts\` — entry point

## Conventions

- Named exports everywhere
`

function setupMocks(): void {
  vi.mocked(readLayer).mockImplementation((_slug: string, layer: string) => {
    if (layer === 'context') return MOCK_CONTEXT
    if (layer === 'rules') return MOCK_RULES
    if (layer === 'codebase') return MOCK_CODEBASE
    return ''
  })
}

// ---------------------------------------------------------------------------
// exportAgentsMd
// ---------------------------------------------------------------------------

describe('exportAgentsMd', () => {
  beforeEach(setupMocks)

  it('includes generated-by header', () => {
    const output = exportAgentsMd('my-project')
    expect(output).toContain('generated by mexai')
    expect(output).toContain('AGENTS.md')
  })

  it('includes do-not-edit warning', () => {
    const output = exportAgentsMd('my-project')
    expect(output).toContain('do not edit directly')
  })

  it('includes all three layers', () => {
    const output = exportAgentsMd('my-project')
    expect(output).toContain('Agent Rules')
    expect(output).toContain('My Project')
    expect(output).toContain('Key Files')
  })

  it('orders layers: rules → context → codebase', () => {
    const output = exportAgentsMd('my-project')
    const rulesIdx = output.indexOf('Agent Rules')
    const contextIdx = output.indexOf('My Project')
    const codebaseIdx = output.indexOf('Key Files')
    expect(rulesIdx).toBeLessThan(contextIdx)
    expect(contextIdx).toBeLessThan(codebaseIdx)
  })

  it('respects token ceiling (output is reasonable size)', () => {
    const output = exportAgentsMd('my-project')
    // 700 tokens ≈ 2800 chars. With headers and separators, allow some overhead
    expect(output.length).toBeLessThan(10_000)
  })
})

